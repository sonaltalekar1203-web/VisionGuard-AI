
import os

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    Image,
    PageBreak
)


def generate_inspection_report(
    result,
    original_path,
    heatmap_path,
    overlay_path,
    output_path
):

    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    document = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "VisionGuardTitle",
        parent=styles["Title"],
        fontSize=23,
        textColor=colors.HexColor("#17365D"),
        spaceAfter=8
    )

    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#17365D"),
        spaceBefore=12,
        spaceAfter=8
    )

    story = []

    # HEADER
    story.append(
        Paragraph("VISIONGUARD AI", title_style)
    )

    story.append(
        Paragraph(
            "Industrial Defect Detection & Quality Inspection Report",
            styles["Normal"]
        )
    )

    story.append(Spacer(1, 12))

    # INSPECTION SUMMARY
    story.append(
        Paragraph("1. Inspection Summary", heading_style)
    )

    prediction = result["result"]

    status_color = (
        colors.red
        if prediction == "Defective"
        else colors.green
    )

    summary_data = [
        ["Parameter", "Inspection Result"],
        ["Filename", result["filename"]],
        ["Anomaly Score", f"{result['anomaly_score']:.4f}"],
        ["Classification", prediction],
        ["Decision Threshold", f"{result['threshold']:.4f}"],
        ["Inspection Time", result["inspected_at"]],
        ["Image Dimensions",
         f"{result['image_width']} x {result['image_height']}"]
    ]

    summary_table = Table(
        summary_data,
        colWidths=[55 * mm, 105 * mm]
    )

    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0),
         colors.HexColor("#17365D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("BACKGROUND", (0, 1), (-1, -1),
         colors.HexColor("#F2F5F9")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("TEXTCOLOR", (1, 3), (1, 3), status_color),
        ("FONTNAME", (1, 3), (1, 3), "Helvetica-Bold")
    ]))

    story.append(summary_table)
    story.append(Spacer(1, 16))

    # IMAGE ANALYSIS
    story.append(
        Paragraph("2. Visual Inspection", heading_style)
    )

    image_width = 78 * mm
    image_height = 78 * mm

    image_data = [[
        Image(original_path, width=image_width, height=image_height),
        Image(heatmap_path, width=image_width, height=image_height)
    ], [
        Paragraph("Original Product Image", styles["Normal"]),
        Paragraph("Anomaly Heatmap", styles["Normal"])
    ]]

    image_table = Table(
        image_data,
        colWidths=[82 * mm, 82 * mm]
    )

    image_table.setStyle(TableStyle([
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("PADDING", (0, 0), (-1, -1), 5)
    ]))

    story.append(image_table)
    story.append(Spacer(1, 12))

    story.append(
        Paragraph("3. Defect Localization Overlay", heading_style)
    )

    story.append(
        Image(
            overlay_path,
            width=115 * mm,
            height=115 * mm
        )
    )

    story.append(Spacer(1, 12))

    # DISCLAIMER
    story.append(
        Paragraph("4. Technical Notes", heading_style)
    )

    story.append(
        Paragraph(
            "Inspection performed using the VisionGuard AI "
            "PatchCore anomaly detection model. The classification "
            "uses a provisional development threshold. Independent "
            "validation is required before production deployment.",
            styles["BodyText"]
        )
    )

    story.append(Spacer(1, 16))

    story.append(
        Paragraph(
            "Generated by VisionGuard AI | "
            "PyTorch | Anomalib | FastAPI | Streamlit",
            styles["Italic"]
        )
    )

    document.build(story)

    return output_path
